#!/usr/bin/env python3
"""Baseline rule-based detectors + evaluation on the synthetic dataset.

    python scripts/detect.py [data/synthetic_events.jsonl]

Prints per-rule and overall event-level precision / recall / F1.
These rules are deliberately simple baselines. Because the dataset is synthetic and
generated by the same author, high scores here are NOT evidence of real-world performance.
"""
import json
import re
import statistics
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "data" / "synthetic_events.jsonl"
events = [json.loads(l) for l in path.open()]
ts = lambda e: datetime.fromisoformat(e["ts"].replace("Z", "+00:00"))

# R1 brute force: >= 6 failed logins from one src_ip within 60 s
def r1(evs):
    hits, by_ip = set(), defaultdict(list)
    for e in evs:
        if e["source"] == "auth" and e.get("outcome") == "failure" and e.get("src_ip"):
            by_ip[e["src_ip"]].append(e)
    for ip, lst in by_ip.items():
        lst.sort(key=ts)
        for i in range(len(lst)):
            win = [x for x in lst[i:] if (ts(x) - ts(lst[i])).total_seconds() <= 60]
            if len(win) >= 6:
                hits.update(x["event_id"] for x in win)
    return hits

# R2 indirect prompt injection: instruction-override pattern in tool output, plus
#    any non-allowlisted egress tool call on the agent
PATTERN = re.compile(r"ignore (all |your )?previous|disregard your|\[system:|new instruction|admin mode", re.I)
EGRESS_ALLOW = {"ehr.clinic.example"}
def r2(evs):
    hits = set()
    for e in evs:
        if e["source"] != "llm_agent":
            continue
        if PATTERN.search(e.get("tool_output") or ""):
            hits.add(e["event_id"])
        if e.get("tool") == "http_post" and e.get("dest") not in EGRESS_ALLOW:
            hits.add(e["event_id"])
    return hits

# R3 federated poisoning: update norm > median + 3*MAD within the round
def r3(evs):
    hits, rounds = set(), defaultdict(list)
    for e in evs:
        if e["source"] == "federated":
            rounds[e["fl_round"]].append(e)
    for lst in rounds.values():
        norms = [x["update_norm"] for x in lst]
        med = statistics.median(norms)
        mad = statistics.median(abs(n - med) for n in norms) or 1e-9
        hits.update(x["event_id"] for x in lst if x["update_norm"] > med + 3 * mad)
    return hits

# R4 ransomware: mass rename burst, or shadow-copy deletion
def r4(evs):
    return {e["event_id"] for e in evs if (e.get("file_renames_5s") or 0) >= 20
            or "delete shadows" in e["message"].lower()}

# R5 encoded PowerShell spawned by Outlook
def r5(evs):
    return {e["event_id"] for e in evs if e.get("image") == "powershell.exe"
            and (e.get("parent_image") or "").upper() == "OUTLOOK.EXE" and "-EncodedCommand" in e["message"]}

RULES = {"R1 brute_force": (r1, "bruteforce"), "R2 prompt_injection": (r2, "prompt_injection"),
         "R3 fl_poisoning": (r3, "federated_poisoning"), "R4 ransomware": (r4, "ransomware"),
         "R5 phishing_powershell": (r5, "phishing")}

def prf(pred, truth):
    tp = len(pred & truth); fp = len(pred - truth); fn = len(truth - pred)
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return tp, fp, fn, p, r, f

print(f"Dataset: {path.name}  events={len(events)}  malicious={sum(e['label']=='malicious' for e in events)}\n")
print(f"{'rule':24} {'TP':>4} {'FP':>4} {'FN':>4} {'prec':>6} {'rec':>6} {'F1':>6}")
all_pred = set()
for name, (fn, scen) in RULES.items():
    pred = fn(events); all_pred |= pred
    truth = {e["event_id"] for e in events if e["scenario"] == scen and e["label"] == "malicious"}
    tp, fp, fn_, p, r, f = prf(pred, truth)
    print(f"{name:24} {tp:4} {fp:4} {fn_:4} {p:6.2f} {r:6.2f} {f:6.2f}")
truth_all = {e["event_id"] for e in events if e["label"] == "malicious"}
tp, fp, fn_, p, r, f = prf(all_pred, truth_all)
print(f"{'OVERALL':24} {tp:4} {fp:4} {fn_:4} {p:6.2f} {r:6.2f} {f:6.2f}")
